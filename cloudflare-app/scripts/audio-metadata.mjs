/**
 * Keep planning tied to the exact deployed recordings. Run after replacing audio;
 * tests compare SHA-256 hashes so stale durations cannot silently reach production.
 */
import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const files = {
  gong: 'gong.mp3', intro: 'chanting/default-intro.mp3',
  instructions: 'instructions.mp3', outroChanting: 'chanting/default-outro.mp3',
  metta: 'metta.mp3', closing: 'outro.mp3',
  mettaFadeIn: 'metta-fade-in.mp3', closingFadeIn: 'outro-fade-in.mp3',
  guidedShort: 'guided/short.mp3', guidedLong: 'guided/long.mp3',
}
const catalog = Object.fromEntries(Object.entries(files).map(([key, file]) => {
  const path = fileURLToPath(new URL('../public/audio/' + file, import.meta.url))
  const result = JSON.parse(execFileSync('ffprobe', [
    '-v', 'error', '-show_entries', 'format=duration', '-of', 'json', path,
  ], { encoding: 'utf8' }))
  const durationSeconds = Number(result.format.duration)
  if (!Number.isFinite(durationSeconds) || durationSeconds <= 0) throw Error('Invalid duration: ' + file)
  return [key, {
    audioSrc: '/audio/' + file, durationSeconds,
    sha256: createHash('sha256').update(readFileSync(path)).digest('hex'),
  }]
}))
writeFileSync(new URL('../src/audioCatalog.ts', import.meta.url),
  '// Generated by npm run audio:metadata. Do not edit measured durations by hand.\n' +
  'export const audioCatalog = ' + JSON.stringify(catalog, null, 2) + ' as const\n')
